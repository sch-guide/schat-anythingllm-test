const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(),"schat-excel-test-"));
process.env.STORAGE_DIR = tmp;
process.env.NODE_ENV = "test";
const XLSX = require("xlsx");
const { processSingleFile } = require("../../processSingleFile");
test.after(() => {
  if (path.dirname(path.resolve(tmp)) !== path.resolve(os.tmpdir())) throw Error("UNSAFE_TEST_CLEANUP");
  fs.rmSync(tmp,{recursive:true,force:true});
});
for (const extension of ["xlsx","xls"]) test(`실제 ${extension} 업로드 변환: 앞자리 0·다중 시트·파일 식별 보존`, async () => {
  const filename=`전화번호부.${extension}`, file=path.join(tmp,filename);
  const book=XLSX.utils.book_new();
  const sheet=XLSX.utils.aoa_to_sheet([["성명","단축번호","내선번호"],["가나다",123,"0056"],["라마바",null,"0789"]]);
  sheet.B2.z="0000";
  XLSX.utils.book_append_sheet(book,sheet,"연락처");
  XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet([["부서","직통번호"],["가상팀","010-0000-0000"]]),"부서");
  XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet([]),"빈 시트");
  XLSX.writeFile(book,file,{bookType:extension==="xls" ? "biff8" : "xlsx"});
  const documentId=`fake-workbook-${extension}`;
  const result=await processSingleFile(filename,{absolutePath:file},{title:filename,document_id:documentId});
  assert.equal(result.success,true,result.reason);
  assert.equal(result.documents.length,2);
  assert.equal(new Set(result.documents.map(d=>d.location)).size,2,"한글 시트 이름이 내부 파일에서 충돌하면 안 됨");
  const documents=result.documents.map(d=>JSON.parse(fs.readFileSync(path.join(tmp,"documents",d.location),"utf8")));
  assert.ok(documents.every(d=>d.document_id===documentId && d.title===filename));
  const key=require("node:crypto").createHash("sha256").update(documentId).digest("hex");
  assert.deepEqual(fs.readFileSync(path.join(tmp,"original-spreadsheets",key+"."+extension)),fs.readFileSync(file));
  const {previewSpreadsheet}=require("../../../server/utils/originalSpreadsheet");
  const preview=previewSpreadsheet(path.join(tmp,"original-spreadsheets",key+"."+extension),{sheet:"연락처"});
  assert.equal(preview.rows[1].cells[1],"0123");
  assert.equal(preview.rows[1].cells[2],"0056");
  assert.deepEqual(preview.sheets,["연락처","부서","빈 시트"]);
  assert.deepEqual(documents.map(d=>d.section),["시트: 연락처","시트: 부서"]);
  assert.match(documents[0].pageContent,/단축번호: 0123 \| 내선번호: 0056/);
  assert.match(documents[0].pageContent,/단축번호: \[빈 칸\] \| 내선번호: 0789/);
  const direct=await processSingleFile(filename,{absolutePath:file,parseOnly:true});
  assert.equal(direct.success,true,direct.reason);
  assert.equal(direct.documents.length,1);
});
